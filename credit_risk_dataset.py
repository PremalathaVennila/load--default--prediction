import pandas as pd
import matplotlib.pyplot as plt
from sklearn.model_selection import train_test_split
from sklearn.compose import ColumnTransformer
from sklearn.pipeline import Pipeline
from sklearn.impute import SimpleImputer
from sklearn.preprocessing import OneHotEncoder, StandardScaler
from sklearn.linear_model import LogisticRegression
from sklearn.ensemble import RandomForestClassifier, GradientBoostingClassifier
from sklearn.metrics import (accuracy_score, precision_score, recall_score,
                             f1_score, roc_auc_score, confusion_matrix,
                             ConfusionMatrixDisplay, classification_report)

# ---------- Phase 1: load and inspect ----------
df = pd.read_csv("credit_risk_dataset.csv")
print(df.shape)                       # rows, columns -> your [N,NNN]
print(df.isnull().sum())              # missing values per column
print(df["loan_status"].value_counts(normalize=True))   # default rate

# ---------- Phase 2: basic cleaning ----------
df = df.drop_duplicates()
df = df[df["person_age"] < 100]       # remove impossible ages
print("Rows after cleaning:", len(df))

# ---------- Phase 3: quick EDA ----------
print(df.groupby("loan_grade")["loan_status"].mean().round(3))
df.groupby("loan_grade")["loan_status"].mean().plot(kind="bar", title="Default rate by loan grade")
plt.ylabel("Default rate"); plt.tight_layout(); plt.savefig("default_by_grade.png"); plt.close()

# ---------- Phase 4: prepare data ----------
X = df.drop(columns="loan_status")
y = df["loan_status"]
num_cols = X.select_dtypes(include="number").columns
cat_cols = X.select_dtypes(exclude="number").columns

prep = ColumnTransformer([
    ("num", Pipeline([("imp", SimpleImputer(strategy="median")),
                      ("sc", StandardScaler())]), num_cols),
    ("cat", Pipeline([("imp", SimpleImputer(strategy="most_frequent")),
                      ("oh", OneHotEncoder(handle_unknown="ignore"))]), cat_cols),
])

X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.2, stratify=y, random_state=42)

# ---------- Phase 5: train 3 models ----------
models = {
    "Logistic Regression": LogisticRegression(max_iter=1000, class_weight="balanced"),
    "Random Forest": RandomForestClassifier(n_estimators=200, class_weight="balanced",
                                            random_state=42, n_jobs=-1),
    "Gradient Boosting": GradientBoostingClassifier(random_state=42),
}
fitted, rows = {}, []
for name, model in models.items():
    pipe = Pipeline([("prep", prep), ("model", model)])
    pipe.fit(X_train, y_train)
    pred = pipe.predict(X_test)
    proba = pipe.predict_proba(X_test)[:, 1]
    fitted[name] = pipe
    rows.append({"Model": name,
                 "Accuracy": accuracy_score(y_test, pred),
                 "Precision": precision_score(y_test, pred),
                 "Recall": recall_score(y_test, pred),
                 "F1": f1_score(y_test, pred),
                 "ROC-AUC": roc_auc_score(y_test, proba)})

# ---------- Phase 6: compare ----------
results = pd.DataFrame(rows).set_index("Model").round(3)
print(results)

best_name = results["ROC-AUC"].idxmax()
best = fitted[best_name]
print("Best model:", best_name)
print(classification_report(y_test, best.predict(X_test)))
ConfusionMatrixDisplay(confusion_matrix(y_test, best.predict(X_test))).plot()
plt.title(best_name); plt.savefig("confusion_matrix.png"); plt.close()

# ---------- Phase 7: what drives default? ----------
rf = fitted["Random Forest"]
names = rf.named_steps["prep"].get_feature_names_out()
imp = pd.Series(rf.named_steps["model"].feature_importances_, index=names)
top = imp.sort_values(ascending=False).head(10)
print(top.round(3))
top.sort_values().plot(kind="barh", title="Top 10 factors behind default")
plt.tight_layout(); plt.savefig("feature_importance.png"); plt.close()

